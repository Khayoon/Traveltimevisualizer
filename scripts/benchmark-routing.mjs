import fs from 'node:fs/promises';
import { performance } from 'node:perf_hooks';
import { createHash } from 'node:crypto';
import { buildGraph, route, calculateReachable, arrivalAt } from '../src/routing.js';
import { cities } from '../src/cities.js';

const mode = process.argv[2] || 'gta';
const report = { mode };
const memory = () => Object.fromEntries(Object.entries(process.memoryUsage()).map(([key, value]) => [key, Math.round(value / 1048576)]));
const measure = (fn) => { const start = performance.now(); const value = fn(); return { value, ms: Math.round(performance.now() - start) }; };
const raw = await fs.readFile(new URL(`../public/data/${mode}.json`, import.meta.url), 'utf8');
report.dataSha256 = createHash('sha256').update(raw).digest('hex');
const parsed = measure(() => JSON.parse(raw));
const data = parsed.value;
report.bytes = Buffer.byteLength(raw);
report.nodeCount = data.nodes.length;
report.edgeCount = data.edges.length;
report.parseMs = parsed.ms;
report.afterParseMiB = memory();
const built = measure(() => buildGraph(data, { cacheSize: 3 }));
const graph = built.value;
report.buildMs = built.ms;
report.afterBuildMiB = memory();
const routed = measure(() => route(graph, [-79.3832, 43.6532]));
const result = routed.value;
report.torontoRouteMs = routed.ms;
report.afterRouteMiB = memory();
report.maxMinutes = result.maxMinutes;
report.snap = result.snap;
report.totalKm = result.totalKm;
report.connectedKm = result.connectedKm;
report.atOneHour = calculateReachable(data, result, 60);
report.atThreeHours = calculateReachable(data, result, 180);
report.atMax = calculateReachable(data, result, result.maxMinutes);
report.destinationResults = cities.filter(c => mode === 'ontario' || c.gta).map(c => ({ name: c.name, ...arrivalAt(graph, result, c.coordinates) }));
report.destinationResults = report.destinationResults.map(({ name, minutes, snap }) => ({ name, minutes: Number.isFinite(minutes) ? Math.round(minutes * 10) / 10 : null, snapKm: Math.round(snap.distanceKm * 1000) / 1000 }));
report.tenThousandSliderReadsMs = measure(() => { for (let i = 0; i < 10000; i++) calculateReachable(data, result, result.maxMinutes * i / 9999); }).ms;
report.cacheReadMs = measure(() => route(graph, [-79.3832, 43.6532])).ms;
report.resultArrayMiB = Math.round(Object.values(result).reduce((sum, value) => sum + (ArrayBuffer.isView(value) ? value.byteLength : 0), 0) / 1048576);
const artifactDirectory = new URL('../artifacts/', import.meta.url);
const artifactPath = new URL('route-benchmark.json', artifactDirectory);
await fs.mkdir(artifactDirectory, { recursive: true });
let combined = {};
try { combined = JSON.parse(await fs.readFile(artifactPath, 'utf8')); } catch {}
combined[mode] = { ...report, measuredAt: new Date().toISOString(), nodeVersion: process.version, note: 'Local Node benchmark of full road graph; RSS includes parsed JSON, graph, route, and temporary allocations. Times are free-flow model estimates without traffic or intersection delays.' };
await fs.writeFile(artifactPath, JSON.stringify(combined, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
